"""Markdown report rendering."""

from __future__ import annotations

from datetime import datetime
from typing import Any

__all__ = ["render_markdown_report"]


def _format_datetime(iso_string: str | None) -> str:
    if not iso_string:
        return "N/A"
    try:
        dt = datetime.fromisoformat(iso_string.replace("Z", "+00:00"))
        return dt.strftime("%Y-%m-%d %H:%M:%S UTC")
    except Exception:
        return iso_string


def render_markdown_report(report: dict[str, Any]) -> str:
    """Render a complete Markdown report from the combined JSON structure."""

    lines = [
        "# SentinelForge Detection Engineering Report",
        "",
        f"**Generated:** {_format_datetime(report.get('generated_at'))}",
        "",
        "---",
        "",
    ]

    # Validation section
    validation = report.get("validation")
    if validation:
        lines.extend(_render_validation_section(validation))
        lines.append("")

    # Conversion section
    conversion = report.get("conversion")
    if conversion:
        lines.extend(_render_conversion_section(conversion))
        lines.append("")

    # Testing section
    testing = report.get("testing")
    if testing:
        lines.extend(_render_testing_section(testing))
        lines.append("")

    # Coverage section
    coverage = report.get("coverage")
    if coverage:
        lines.extend(_render_coverage_section(coverage))
        lines.append("")

    lines.append("---")
    lines.append("*Report generated by SentinelForge*")
    return "\n".join(lines)


def _render_validation_section(validation: dict[str, Any]) -> list[str]:
    lines = [
        "## Validation Results",
        "",
        f"- **Rules discovered:** {validation.get('rules_discovered', 0)}",
        f"- **Rules valid:** {validation.get('rules_valid', 0)}",
        f"- **Rules invalid:** {validation.get('rules_invalid', 0)}",
        f"- **Strict mode:** {validation.get('strict', False)}",
        "",
    ]

    issues = validation.get("issues", [])
    errors = [i for i in issues if i.get("severity") == "error"]
    warnings = [i for i in issues if i.get("severity") == "warning"]

    if errors:
        lines.append("### Errors")
        lines.append("")
        for issue in errors:
            lines.append(f"- `{issue.get('code', 'unknown')}` {issue.get('message', '')}")
            if issue.get("rule_path"):
                lines.append(f"  - File: {issue['rule_path']}")
            if issue.get("field"):
                lines.append(f"  - Field: {issue['field']}")
        lines.append("")

    if warnings:
        lines.append("### Warnings")
        lines.append("")
        for issue in warnings:
            lines.append(f"- `{issue.get('code', 'unknown')}` {issue.get('message', '')}")
            if issue.get("rule_path"):
                lines.append(f"  - File: {issue['rule_path']}")
            if issue.get("field"):
                lines.append(f"  - Field: {issue['field']}")
        lines.append("")

    return lines


def _render_conversion_section(conversion: dict[str, Any]) -> list[str]:
    lines = [
        "## Conversion Results",
        "",
        f"- **Backend:** {conversion.get('backend', 'unknown')}",
        f"- **Output directory:** {conversion.get('output_directory', 'N/A')}",
        f"- **Total rules:** {len(conversion.get('outcomes', []))}",
        f"- **Converted:** {len([o for o in conversion.get('outcomes', []) if o.get('converted')])}",
        f"- **Rejected:** {len([o for o in conversion.get('outcomes', []) if not o.get('converted')])}",
        "",
    ]

    converted = [o for o in conversion.get("outcomes", []) if o.get("converted")]
    if converted:
        lines.append("### Converted Rules")
        lines.append("")
        for outcome in converted:
            lines.append(f"- **{outcome['title']}** (Wazuh ID: {outcome.get('wazuh_rule_id', 'N/A')})")
            lines.append(f"  - Source: {outcome['rule_path']}")
            lines.append(f"  - Output: {outcome.get('output_path', 'N/A')}")
        lines.append("")

    rejected = [o for o in conversion.get("outcomes", []) if not o.get("converted")]
    if rejected:
        lines.append("### Rejected Rules")
        lines.append("")
        for outcome in rejected:
            lines.append(f"- **{outcome['title']}**")
            lines.append(f"  - Source: {outcome['rule_path']}")
            lines.append(f"  - Reason: {outcome.get('message', 'Unknown')}")
            if outcome.get("limitation"):
                lines.append(f"  - Limitation: {outcome['limitation']}")
            if outcome.get("feature"):
                lines.append(f"  - Feature: {outcome['feature']}")
        lines.append("")

    warnings = conversion.get("warnings", [])
    if warnings:
        lines.append("### Conversion Warnings")
        lines.append("")
        for warning in warnings:
            lines.append(f"- {warning}")
        lines.append("")

    return lines


def _render_testing_section(testing: dict[str, Any]) -> list[str]:
    lines = [
        "## Testing Results",
        "",
        f"- **Fixtures discovered:** {testing.get('fixtures_discovered', 0)}",
        f"- **Fixtures passed:** {testing.get('fixtures_passed', 0)}",
        f"- **Fixtures failed:** {testing.get('fixtures_failed', 0)}",
        f"- **Fixtures not evaluated:** {testing.get('fixtures_not_evaluated', 0)}",
        f"- **Wazuh integration:** {testing.get('wazuh_integration', 'NOT RUN')}",
        "",
    ]

    wazuh_detail = testing.get("wazuh_detail")
    if wazuh_detail:
        lines.append(f"- **Wazuh detail:** {wazuh_detail}")
        lines.append("")

    unit_passed = testing.get("unit_tests_passed")
    unit_failed = testing.get("unit_tests_failed")
    unit_skipped = testing.get("unit_tests_skipped")
    if unit_passed is not None:
        lines.append(f"- **Unit tests passed:** {unit_passed}")
    if unit_failed is not None:
        lines.append(f"- **Unit tests failed:** {unit_failed}")
    if unit_skipped is not None:
        lines.append(f"- **Unit tests skipped:** {unit_skipped}")
    lines.append("")

    results = testing.get("results", [])
    failed_results = [r for r in results if not r.get("passed", True)]
    if failed_results:
        lines.append("### Failed Fixtures")
        lines.append("")
        for result in failed_results:
            lines.append(f"- **{result['fixture']}** ({result['rule_path']})")
            lines.append(f"  - Expected: {result['expectation']}")
            lines.append(f"  - Got: {result['structured']}")
            if result.get("detail"):
                lines.append(f"  - Detail: {result['detail']}")
        lines.append("")

    return lines


def _render_coverage_section(coverage: dict[str, Any]) -> list[str]:
    lines = [
        "## Coverage Metrics",
        "",
        f"- **Total rules:** {coverage.get('rules_total', 0)}",
        f"- **Rules with positive fixture:** {coverage.get('rules_with_positive_fixture', 0)}",
        f"- **Rules with negative fixture:** {coverage.get('rules_with_negative_fixture', 0)}",
        f"- **Rules covered (any fixture):** {coverage.get('rules_covered', 0)}",
        f"- **Rules converted:** {coverage.get('rules_converted', 0)}",
        f"- **Rules rejected:** {coverage.get('rules_rejected', 0)}",
        "",
    ]

    platform_counts = coverage.get("platform_counts", {})
    if platform_counts:
        lines.append("### Platform Distribution")
        lines.append("")
        for platform, count in sorted(platform_counts.items()):
            lines.append(f"- {platform}: {count}")
        lines.append("")

    techniques = coverage.get("techniques", {})
    if techniques:
        lines.append("### MITRE ATT&CK Coverage")
        lines.append("")
        for technique_id, rule_ids in sorted(techniques.items()):
            lines.append(f"- **{technique_id}**: {len(rule_ids)} rule(s)")
        lines.append("")

    uncovered = coverage.get("uncovered_rules", [])
    if uncovered:
        lines.append("### Uncovered Rules (no fixtures)")
        lines.append("")
        for rule_path in uncovered:
            lines.append(f"- {rule_path}")
        lines.append("")

    return lines
